import fs from 'node:fs/promises';
import path from 'node:path';
import type { RecentProject } from '../../../shared/domain/projectTypes';

const FILE_NAME = 'recent-projects.json';

export class RecentProjectsService {
  constructor(private readonly storageDir: string, private readonly maxEntries = 20) {}

  private get filePath(): string {
    return path.join(this.storageDir, FILE_NAME);
  }

  async list(): Promise<RecentProject[]> {
    try {
      const raw = await fs.readFile(this.filePath, 'utf8');
      const parsed = JSON.parse(raw) as unknown;
      return Array.isArray(parsed) ? parsed.filter(this.isRecentProject).slice(0, this.maxEntries) : [];
    } catch {
      return [];
    }
  }

  async upsert(item: RecentProject): Promise<RecentProject[]> {
    const existing = await this.list();
    const next = [item, ...existing.filter((entry) => entry.projectId !== item.projectId)].slice(0, this.maxEntries);
    await fs.mkdir(this.storageDir, { recursive: true });
    await fs.writeFile(this.filePath, JSON.stringify(next, null, 2), 'utf8');
    return next;
  }

  async remove(projectId: string, protectedPaths: string[] = []): Promise<RecentProject[]> {
    const existing = await this.list();
    const entry = existing.find((item) => item.projectId === projectId);
    const next = existing.filter((item) => item.projectId !== projectId);
    if (entry && !next.some((item) => path.resolve(item.projectFilePath) === path.resolve(entry.projectFilePath))) {
      await this.removeOwnedFiles(entry, protectedPaths);
    }
    await fs.mkdir(this.storageDir, { recursive: true });
    await fs.writeFile(this.filePath, JSON.stringify(next, null, 2), 'utf8');
    return next;
  }

  private async removeOwnedFiles(entry: RecentProject, protectedPaths: string[]): Promise<void> {
    const projectFile = path.resolve(entry.projectFilePath);
    if (path.basename(projectFile).toLowerCase() !== 'project.json') return;
    const folder = path.dirname(projectFile);
    const folderInfo = await fs.lstat(folder).catch(() => null);
    if (!folderInfo?.isDirectory() || folderInfo.isSymbolicLink()) return;
    const info = await fs.lstat(projectFile).catch(() => null);
    if (info && (!info.isFile() || info.isSymbolicLink())) return;
    if (info) {
      const project = JSON.parse(await fs.readFile(projectFile, 'utf8')) as { projectId?: string; projectDir?: string };
      if (project.projectId !== entry.projectId || path.resolve(project.projectDir ?? '') !== folder) throw new Error('Identitas folder project tidak sesuai; berkas tidak dihapus.');
    } else if (!/-[0-9a-f]{8}$/i.test(path.basename(folder))) {
      // An existing recent entry can identify an orphan only when its folder
      // has the unique suffix generated by the application's project creator.
      return;
    }
    const lockedPaths = protectedPaths.map((item) => path.resolve(item));
    // These are generated project artifacts. Keep source media, exported videos,
    // user files and the configured asset library even if located in this folder.
    const cleanedAudio = path.join(folder, 'audio-metadata-cleaned');
    if (!lockedPaths.some((item) => item === cleanedAudio || item.startsWith(`${cleanedAudio}${path.sep}`) || cleanedAudio.startsWith(`${item}${path.sep}`))) {
      const audioInfo = await fs.lstat(cleanedAudio).catch(() => null);
      if (audioInfo?.isDirectory() && !audioInfo.isSymbolicLink()) await fs.rm(cleanedAudio, { recursive: true });
    }
    await fs.rm(path.join(folder, 'seo-analysis-cache.json'), { force: true });
    if (info) await fs.unlink(projectFile);
    await fs.rmdir(folder).catch((error: NodeJS.ErrnoException) => { if (error.code !== 'ENOTEMPTY' && error.code !== 'EEXIST') throw error; });
  }

  private isRecentProject(value: unknown): value is RecentProject {
    if (!value || typeof value !== 'object') return false;
    const entry = value as Record<string, unknown>;
    return [entry.projectId, entry.name, entry.projectFilePath, entry.lastOpenedAt].every((field) => typeof field === 'string' && field.length > 0) && (entry.mainMediaPath === undefined || typeof entry.mainMediaPath === 'string');
  }
}
