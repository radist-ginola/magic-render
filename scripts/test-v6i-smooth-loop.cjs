const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const Module = require('node:module');
const ts = require('typescript');
for (const ext of ['.ts','.tsx']) Module._extensions[ext] = (mod,file) => mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText,file);
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'mrp-v6i-loop-'));
process.env.XDG_CONFIG_HOME=temp;
const {smoothLoopPlan,createSmoothLoopAsset}=require('../src/main/services/overlay/smoothLoopService.ts');
const {defaultOverlayConfig}=require('../src/shared/domain/overlayTypes.ts');
const {lockAsset,unlockAsset}=require('../src/main/services/persistentStore/index.ts');
const run=(program,args)=>{const result=spawnSync(program,args,{encoding:'utf8',timeout:60000});assert.equal(result.status,0,result.stderr);return result.stdout.trim();};
(async()=>{try {
 const plan=smoothLoopPlan(0,4,15);
 assert.equal(plan.frames,42); assert.equal(plan.durationSec,2.8);
 assert.match(plan.filter,/xfade=transition=fade/);
 assert.match(plan.filter,/start_frame=18:end_frame=60/);
 const src=path.join(temp,'overlay.mp4');
 run('ffmpeg',['-v','error','-y','-f','lavfi','-i','testsrc2=size=160x90:rate=15:duration=4','-c:v','libx264','-pix_fmt','yuv420p',src]);
 const asset=await lockAsset('overlay',src,undefined,path.join(temp,'library'));
 const result=await createSmoothLoopAsset(asset,defaultOverlayConfig(),'ffmpeg','ffprobe',path.join(temp,'library'));
 assert.equal(result.asset.menu,'overlay');assert.notEqual(result.asset.assetId,asset.assetId);
 assert(fs.existsSync(result.asset.path));assert(fs.existsSync(asset.path));
 assert.equal(result.asset.config.trim,undefined);
 assert.match(result.asset.metadata.originalName,/smooth-loop\.mp4$/);
 const duration=Number(run('ffprobe',['-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',result.asset.path]));
 assert(Math.abs(duration-result.durationSec)<.1,`${duration} vs ${result.durationSec}`);
 run('ffmpeg',['-v','error','-stream_loop','1','-i',result.asset.path,'-f','null','-']);
 const transparent=path.join(temp,'transparent.mov');
 run('ffmpeg',['-v','error','-y','-f','lavfi','-i','color=c=red@0.5:s=64x64:r=10:d=2,format=rgba','-c:v','qtrle','-pix_fmt','argb',transparent]);
 const alphaAsset=await lockAsset('overlay',transparent,undefined,path.join(temp,'library'));
 await assert.rejects(()=>createSmoothLoopAsset(alphaAsset,defaultOverlayConfig(),'ffmpeg','ffprobe',path.join(temp,'library')),/kanal transparansi/);
 await unlockAsset(result.asset.assetId);
 assert(fs.existsSync(asset.path),'original preserved after duplicate removal');
 console.log('V6I smooth-loop derivation, FFmpeg decode, original preservation PASSED');
}finally{fs.rmSync(temp,{recursive:true,force:true});}})().catch((error)=>{console.error(error);process.exitCode=1});
