const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cp = require('node:child_process');
const ts = require('typescript');
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText, file);
const { PlaylistService } = require('../src/main/services/audio/playlistService.ts');
const { buildAudioConcatCommand } = require('../src/main/services/audio/audioConcatBuilder.ts');
const { buildYoutubeTimestampText } = require('../src/main/services/aiService/timestampGenerator.ts');
const { songLinesFromTimestamp } = require('../src/main/services/aiService/seoFileWriter.ts');
const { buildScheduleWindows } = require('../src/shared/domain/stickerTimeline.ts');
const { buildRelevantTags } = require('../src/main/services/aiService/seoTags.ts');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mrp-v5w-playlist-'));
function run(exe, args) { const value = cp.spawnSync(exe, args, { encoding: 'utf8', timeout: 90000, maxBuffer: 2e6 }); assert.equal(value.status, 0, value.stderr); return value.stdout; }

(async () => { try {
  const source = path.join(root, 'sample.mp3');
  run('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=0.4', '-c:a', 'libmp3lame', source]);
  const files = Array.from({ length: 10 }, (_, i) => { const file = path.join(root, `${String(i + 1).padStart(2, '0')}_old_song_${i + 1}.mp3`); fs.copyFileSync(source, file); return file; });
  const newcomer = path.join(root, '11_new_whiskey_blues.mp3'); fs.copyFileSync(source, newcomer);
  const service = new PlaylistService('ffprobe');
  let project = { name: 'Test', projectDir: root, playlist: { files: [], playbackOrder: [], shuffle: false }, playlistTracks: [] };
  project = await service.importFiles(project, files);
  project = service.remove(project, 4);
  project = await service.importFiles(project, [newcomer]);
  project = service.reorder(project, 9, 0);
  const displayed = project.playlist.playbackOrder;
  assert.equal(displayed.length, 10);
  assert.equal(displayed[0], newcomer);
  assert(!displayed.includes(files[4]), 'Deleted original is still in playlist');
  assert.deepEqual(service.getPlaybackOrder(project).map((track) => track.path), displayed);
  const shuffled = service.setShuffle(project, true, () => 0);
  const shuffledVisible = service.getPlaybackOrder(shuffled).map((track) => track.path);
  const movedAfterShuffle = service.reorder(shuffled, 9, 0);
  assert.equal(movedAfterShuffle.playlist.shuffle, false);
  assert.equal(movedAfterShuffle.playlist.playbackOrder[0], shuffledVisible[9]);
  assert(!service.remove(shuffled, 0).playlist.files.includes(shuffledVisible[0]), 'Remove must target the visible shuffled item');
  const plan = service.buildComposition(project);
  assert.deepEqual(plan.orderedTracks.map((track) => track.path), displayed, 'FFmpeg plan does not follow the visible order');
  const audio = path.join(root, 'final.aac');
  const command = buildAudioConcatCommand('ffmpeg', plan, audio);
  assert.equal(command.args[command.args.indexOf('-i') + 1], newcomer, 'First encoded input should be the newly moved track');
  run(command.executable, ['-hide_banner', '-loglevel', 'error', ...command.args]);
  assert(fs.statSync(audio).size > 1000);
  const chapters = buildYoutubeTimestampText({ project, audioPlan: plan, finalDurationSeconds: plan.totalDurationSeconds, introDurationSeconds: 0, outputVideoPath: path.join(root, 'final.mp4') });
  assert(chapters.startsWith('00:00 New Whiskey Blues\n'), chapters);
  assert(!chapters.includes('Old Song 5'), chapters);
  assert.equal(songLinesFromTimestamp(chapters, true).length, 10);
  assert.equal(require('../src/main/services/aiService/timestampGenerator.ts').cleanTrackTitle('[04]_LAST_GLASS'), 'Last Glass');
  assert.deepEqual(buildScheduleWindows({ mode: 'iterative', iterativeCount: 3, timestamps: [] }, 370, 4), [{ startSec: 180, endSec: 184 }, { startSec: 360, endSec: 364 }]);
  const analysis = { visualAnalysis: 'An amber whiskey lounge at midnight.', audienceIntent: 'Late-night listeners', visualEvidence: { observed: ['amber lounge', 'a glass of whiskey'] }, keywordsPrimary: ['amber lounge blues', 'whiskey blues', ...Array.from({ length: 48 }, (_, i) => `slow blues mood ${i}`)], keywordsSecondary: ['midnight whiskey blues', ...Array.from({ length: 49 }, (_, i) => `relaxing blues mood ${i}`)] };
  const tags = buildRelevantTags('whiskey blues', 'slow blues', analysis);
  assert.equal(tags[0], 'whiskey blues'); assert(tags.includes('amber lounge blues')); assert(tags.join(', ').length < 500);
  console.log('V5W: remove + import + reorder, FFmpeg audio, chapters, sticker interval, relevant tag limit PASSED');
} finally { fs.rmSync(root, { recursive: true, force: true }); } })().catch((error) => { console.error(error); process.exitCode = 1; });
